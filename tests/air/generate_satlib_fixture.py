#!/usr/bin/env python3
"""Generate a Dafny semantic-resolution fixture from real AIR SATLIB CNF input."""
import hashlib, json, pathlib, sys
AIR=pathlib.Path(sys.argv[1])
DEST=pathlib.Path(__file__).with_name("satlib_case_study.dfy")
manifest=json.loads((AIR/"benchmarks/satlib/manifest.json").read_text())
cases=[
 ("uf50-01.cnf", "AirUF50"),
 ("hole7.cnf", "AirHole7"),
 ("dubois30.cnf", "AirDubois30"),
]
metadata=[]
out=["// MACHINE GENERATED by generate_satlib_fixture.py. Do not claim this is a SAT solver.",
     "// Each Dafny declaration represents an original clause from the AIR SATLIB corpus.",
     "// Sources: https://github.com/Formal-Computing/cdcl-sat-solver/tree/88247ab/benchmarks/satlib",
     "// Original SATLIB: https://www.cs.ubc.ca/~hoos/SATLIB/",
     "module AIR_Semantics {",
     "  function ClauseCount(clauses: seq<seq<int>>): nat { |clauses| }",
     "  function NonEmpty(c: seq<int>): bool { |c| > 0 }",
     "}",
     ""]
for filename,module in cases:
   source=AIR/"benchmarks/satlib/cnf"/filename
   content=source.read_bytes()
   digest=hashlib.sha256(content).hexdigest()
   info=next(x for x in manifest["benchmarks"] if x["file"]==filename)
   assert digest==info["sha256"], "upstream input checksum mismatch"
   nvars=nclauses=None
   vals=[]; clauses=[]; done=False
   for line in content.decode().splitlines():
      line=line.strip()
      if not line or line.startswith("c"): continue
      if line.startswith("p "):
         _,fmt,nvars,nclauses=line.split()
         assert fmt=="cnf"
         nvars=int(nvars); nclauses=int(nclauses);continue
      if line=="%": done=True;continue
      if done:continue
      for token in line.split():
         v=int(token)
         if v==0:
            assert vals,"Empty clause not expected in these original instances"
            clauses.append(vals);vals=[]
         else: vals.append(v)
   assert not vals
   assert len(clauses)==nclauses==info["clauses"]
   assert all(0<abs(v)<=nvars for c in clauses for v in c)
   out += [f"// {filename} : {info['expected']}; {nvars} vars, {nclauses} clauses; SHA-256 {digest}",
           f"module {module} {{",
           f"  const VarCount: nat := {nvars}"]
   for i,c in enumerate(clauses):
       out.append(f"  const C{i:03d}: seq<int> := [{', '.join(map(str,c))}]")
   out.append("  const Clauses: seq<seq<int>> := [")
   for i in range(0,len(clauses),10):
      out.append("    "+", ".join(f"C{k:03d}" for k in range(i,min(i+10,len(clauses))))+("," if i+10<len(clauses) else ""))
   out.append("  ]")
   out.append("}")
   out.append("")
   metadata.append(dict(file=filename,module=module,variables=nvars,clauses=nclauses,sha256=digest,expected=info["expected"]))
out += ["module AIR_Inspector {",
        "  import UF = AirUF50",
        "  import PH = AirHole7",
        "  import DU = AirDubois30",
        "  function TotalClauses(): nat { |UF.Clauses| + |PH.Clauses| + |DU.Clauses| }",
        "}",
        "module AIR_WorkingEdit {",
        "  function RevisionTag(): int { 10 }",
        "}",
        ""]
DEST.write_text("\n".join(out))
meta=dict(source_repo="Formal-Computing/cdcl-sat-solver",source_revision="88247ab605ee0e3da2aca711885e3340eb78c782",sources=metadata,totals=dict(clauses=sum(x["clauses"] for x in metadata),variables=sum(x["variables"] for x in metadata)),fixture_sha256=hashlib.sha256(DEST.read_bytes()).hexdigest())
DEST.with_suffix(".json").write_text(json.dumps(meta,indent=2)+"\n")
print(json.dumps(meta,indent=2))
